using System.Globalization;
using System.Text;
using CDelta.Ir;

namespace CDelta.Backend.CSharp;

public static class StubWriter
{
    private const string UnsupportedAttribute = "cdelta.Unsupported";
    private const string Indent = "    ";

    private static readonly HashSet<string> _keywords =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    ];

    public static string Write(
        Module module,
        IReadOnlyList<StubMacro> macros,
        IReadOnlyDictionary<string, string> unsupported,
        StubOptions options)
    {
        var writer = new Writer(module, unsupported, options);
        return writer.Run(macros);
    }

    private sealed class Writer(Module module, IReadOnlyDictionary<string, string> unsupported, StubOptions options)
    {
        private readonly StringBuilder _text = new();
        private readonly HashSet<string> _arrays = [];
        private readonly StringBuilder _arrayTypes = new();

        public string Run(IReadOnlyList<StubMacro> macros)
        {
            HashSet<string> keepTypes = ReachableTypes();
            var members = new StringBuilder();
            foreach (string key in module.StructsByKey.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                if (keepTypes.Contains("struct:" + key))
                {
                    WriteStruct(members, module.Structs[module.StructsByKey[key].Index]);
                }
            }

            foreach (string key in module.EnumsByKey.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                if (keepTypes.Contains("enum:" + key))
                {
                    WriteEnum(members, module.Enums[module.EnumsByKey[key].Index]);
                }
            }

            foreach (string key in module.OpaquesByKey.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                if (keepTypes.Contains("opaque:" + key))
                {
                    OpaqueDecl opaque = module.Opaques[module.OpaquesByKey[key].Index];
                    members.Append(Indent).Append("[CName(").Append(Quote(module.Text(opaque.Origin.CName))).Append(")] [Opaque] public struct ")
                        .Append(Identifier(key)).Append(" { }\n\n");
                }
            }

            foreach (StubMacro macro in macros.OrderBy(m => m.Name, StringComparer.Ordinal))
            {
                if (Keeps(macro.Name))
                {
                    WriteMacro(members, macro);
                }
            }

            foreach (string key in module.GlobalsByKey.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                if (Keeps(key))
                {
                    WriteGlobal(members, module.Globals[module.GlobalsByKey[key].Index]);
                }
            }

            foreach (string key in module.FunctionsByKey.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                if (Keeps(key))
                {
                    WriteFunction(members, module.Functions[module.FunctionsByKey[key].Index]);
                }
            }

            _text.Append("// <auto-generated> by cdc from C headers; changes are lost. </auto-generated>\n");
            _text.Append("#pragma warning disable CS0649, CS0169, CS8981, CS1591\n");
            _text.Append("using CDelta;\nusing System;\nusing System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\n\n");
            bool namespaced = options.Namespace.Length > 0;
            if (namespaced)
            {
                _text.Append("namespace ").Append(options.Namespace).Append("\n{\n");
            }

            _text.Append("static unsafe partial class ").Append(options.ClassName).Append("\n{\n");
            _text.Append(_arrayTypes).Append(members);
            _text.Append("}\n");
            if (namespaced)
            {
                _text.Append("}\n");
            }

            return _text.ToString();
        }

        private bool Keeps(string name) => options.Only.Count == 0 || options.Only.Any(prefix => name.StartsWith(prefix, StringComparison.Ordinal));

        private HashSet<string> ReachableTypes()
        {
            var keep = new HashSet<string>();
            var pending = new Stack<TypeId>();
            foreach (FunctionId id in module.FunctionsByKey.Values)
            {
                FunctionDecl function = module.Functions[id.Index];
                if (!Keeps(module.Text(function.Key)))
                {
                    continue;
                }

                pending.Push(function.Return);
                for (int i = 0; i < function.Params.Count; i++)
                {
                    pending.Push(module.Params[function.Params.Start + i].Type);
                }
            }

            foreach (GlobalId id in module.GlobalsByKey.Values)
            {
                if (Keeps(module.Text(module.Globals[id.Index].Key)))
                {
                    pending.Push(module.Globals[id.Index].Type);
                }
            }

            foreach (string key in module.StructsByKey.Keys.Where(Keeps))
            {
                pending.Push(module.Type(new TypeNode(TypeKind.Struct, TypeFlags.None, module.StructsByKey[key].Index, 0)));
            }

            foreach (string key in module.EnumsByKey.Keys.Where(Keeps))
            {
                pending.Push(module.Type(new TypeNode(TypeKind.Enum, TypeFlags.None, module.EnumsByKey[key].Index, 0)));
            }

            foreach (string key in module.OpaquesByKey.Keys.Where(Keeps))
            {
                pending.Push(module.Type(new TypeNode(TypeKind.Opaque, TypeFlags.None, module.OpaquesByKey[key].Index, 0)));
            }

            var seen = new HashSet<int>();
            while (pending.Count > 0)
            {
                TypeId type = pending.Pop();
                if (!seen.Add(type.Index))
                {
                    continue;
                }

                TypeNode node = module.Types[type.Index];
                switch (node.Kind)
                {
                    case TypeKind.Ptr or TypeKind.Slice or TypeKind.Array or TypeKind.Optional:
                        pending.Push(new TypeId(node.A));
                        break;
                    case TypeKind.Fn:
                        SigNode sig = module.Sigs[node.A];
                        pending.Push(sig.Return);
                        foreach (int encoded in module.TypeLists[sig.Params.Index])
                        {
                            pending.Push(SigParam.Decode(encoded).Type);
                        }

                        break;
                    case TypeKind.Struct:
                        StructDecl declaration = module.Structs[node.A];
                        keep.Add("struct:" + module.Text(declaration.Key));
                        for (int i = 0; i < declaration.Fields.Count; i++)
                        {
                            pending.Push(module.Fields[declaration.Fields.Start + i].Type);
                        }

                        break;
                    case TypeKind.Enum:
                        keep.Add("enum:" + module.Text(module.Enums[node.A].Key));
                        break;
                    case TypeKind.Opaque:
                        keep.Add("opaque:" + module.Text(module.Opaques[node.A].Key));
                        break;
                }
            }

            return keep;
        }

        private void WriteStruct(StringBuilder members, StructDecl declaration)
        {
            string key = module.Text(declaration.Key);
            string cName = module.Text(declaration.Origin.CName);
            if (cName.Length > 0)
            {
                members.Append(Indent).Append("[CName(").Append(Quote(cName)).Append(")]\n");
            }

            switch (declaration.Layout)
            {
                case StructLayoutKind.Explicit:
                    members.Append(Indent).Append("[StructLayout(LayoutKind.Explicit)]\n");
                    break;
                case StructLayoutKind.Packed:
                    members.Append(Indent).Append("[StructLayout(LayoutKind.Sequential, Pack = ").Append(declaration.Pack).Append(")]\n");
                    break;
            }

            members.Append(Indent).Append("public struct ").Append(Identifier(key)).Append("\n").Append(Indent).Append("{\n");
            for (int i = 0; i < declaration.Fields.Count; i++)
            {
                FieldDecl field = module.Fields[declaration.Fields.Start + i];
                string name = Identifier(module.Text(field.Name));
                if (declaration.Layout == StructLayoutKind.Explicit)
                {
                    members.Append(Indent).Append(Indent).Append("[FieldOffset(0)] ");
                }
                else if (field.BitWidth != FieldDecl.NoBits)
                {
                    members.Append(Indent).Append(Indent).Append("[Bits(").Append(field.BitWidth).Append(")] ");
                }
                else
                {
                    members.Append(Indent).Append(Indent);
                }

                TypeNode type = module.Types[field.Type.Index];
                if (type.Kind == TypeKind.Array)
                {
                    members.Append(FieldArray(type, name)).Append('\n');
                }
                else
                {
                    members.Append("public ").Append(Spell(field.Type)).Append(' ').Append(name).Append(";\n");
                }
            }

            members.Append(Indent).Append("}\n\n");
        }

        private string FieldArray(TypeNode array, string name)
        {
            var element = new TypeId(array.A);
            string spelled = Spell(element);
            if (IsFixedBufferElement(spelled))
            {
                return "public fixed " + spelled + " " + name + "[" + array.B + "];";
            }

            string arrayType = InlineArrayType(spelled, array.B);
            return "public " + arrayType + " " + name + ";";
        }

        private static bool IsFixedBufferElement(string spelled) =>
            spelled is "bool" or "byte" or "sbyte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "float" or "double";

        private string InlineArrayType(string element, int length)
        {
            string name = "InlineArray_" + new string([.. element.Select(c => char.IsLetterOrDigit(c) ? c : '_')]) + "_" + length;
            if (_arrays.Add(name))
            {
                _arrayTypes.Append(Indent).Append("[InlineArray(").Append(length).Append(")] public struct ").Append(name)
                    .Append(" { public ").Append(element).Append(" _e; }\n\n");
            }

            return name;
        }

        private void WriteEnum(StringBuilder members, EnumDecl declaration)
        {
            string key = module.Text(declaration.Key);
            members.Append(Indent).Append("[CName(").Append(Quote(module.Text(declaration.Origin.CName))).Append(")]\n");
            members.Append(Indent).Append("public enum ").Append(Identifier(key)).Append(" : ").Append(Spell(declaration.Underlying)).Append("\n")
                .Append(Indent).Append("{\n");
            for (int i = 0; i < declaration.Members.Count; i++)
            {
                EnumMember member = module.EnumMembers[declaration.Members.Start + i];
                members.Append(Indent).Append(Indent).Append(Identifier(module.Text(member.Name))).Append(" = ")
                    .Append(member.Value.ToString(CultureInfo.InvariantCulture)).Append(",\n");
            }

            members.Append(Indent).Append("}\n\n");
        }

        private void WriteMacro(StringBuilder members, StubMacro macro)
        {
            string name = Identifier(macro.Name);
            switch (macro.Kind)
            {
                case StubMacroKind.Integer:
                    members.Append(Indent).Append("public const ").Append(MacroIntegerType(macro)).Append(' ').Append(name).Append(" = ")
                        .Append(macro.Integer.ToString(CultureInfo.InvariantCulture)).Append(";\n\n");
                    break;
                case StubMacroKind.Float:
                    string floating = macro.CType == "float" ? "float" : "double";
                    members.Append(Indent).Append("public const ").Append(floating).Append(' ').Append(name)
                        .Append(" = ").Append(FloatLiteral(macro.Float, floating)).Append(";\n\n");
                    break;
                default:
                    members.Append(Indent).Append("public const string ").Append(name).Append(" = ").Append(Quote(macro.Text)).Append(";\n\n");
                    break;
            }
        }

        private static string FloatLiteral(double value, string type)
        {
            if (double.IsNaN(value))
            {
                return type + ".NaN";
            }

            if (double.IsInfinity(value))
            {
                return type + (value > 0 ? ".PositiveInfinity" : ".NegativeInfinity");
            }

            string text = value.ToString("R", CultureInfo.InvariantCulture);
            return type == "float" ? text + "f" : text;
        }

        private static string MacroIntegerType(StubMacro macro) => macro.CType switch
        {
            "unsigned int" => "uint",
            "long" or "long long" => "long",
            "unsigned long" or "unsigned long long" => "ulong",
            "unsigned short" => "ushort",
            "short" => "short",
            "unsigned char" => "byte",
            "signed char" => "sbyte",
            _ => macro.Integer > int.MaxValue || macro.Integer < int.MinValue ? (macro.Integer < 0 ? "long" : "ulong") : "int",
        };

        private void WriteGlobal(StringBuilder members, GlobalDecl global)
        {
            string key = module.Text(global.Key);
            members.Append(Indent).Append("[CName(").Append(Quote(key)).Append(")] public static ");
            TypeNode type = module.Types[global.Type.Index];
            members.Append(Spell(global.Type)).Append(' ').Append(Identifier(key)).Append(";\n\n");
            _ = type;
        }

        private void WriteFunction(StringBuilder members, FunctionDecl function)
        {
            string key = module.Text(function.Key);
            if (unsupported.TryGetValue("function:" + key, out string? reason))
            {
                members.Append(Indent).Append("[Unsupported(").Append(Quote(reason)).Append(")] ");
                members.Append("public static extern void ").Append(Identifier(key)).Append("();\n\n");
                return;
            }

            members.Append(Indent).Append("public static extern ").Append(Spell(function.Return)).Append(' ').Append(Identifier(key)).Append('(');
            for (int i = 0; i < function.Params.Count; i++)
            {
                ParamDecl parameter = module.Params[function.Params.Start + i];
                members.Append(i > 0 ? ", " : string.Empty).Append(Spell(parameter.Type)).Append(' ').Append(Identifier(module.Text(parameter.Name)));
            }

            if (function.Variadic)
            {
                members.Append(function.Params.Count > 0 ? ", " : string.Empty).Append("__arglist");
            }

            members.Append(");\n\n");
        }

        private string Spell(TypeId type)
        {
            TypeNode node = module.Types[type.Index];
            switch (node.Kind)
            {
                case TypeKind.Ptr:
                    return Spell(new TypeId(node.A)) + "*";
                case TypeKind.Fn:
                    SigNode sig = module.Sigs[node.A];
                    var parts = new List<string>();
                    foreach (int encoded in module.TypeLists[sig.Params.Index])
                    {
                        parts.Add(Spell(SigParam.Decode(encoded).Type));
                    }

                    parts.Add(Spell(sig.Return));
                    return "delegate*<" + string.Join(", ", parts) + ">";
                case TypeKind.Struct:
                    return Identifier(module.Text(module.Structs[node.A].Key));
                case TypeKind.Enum:
                    return Identifier(module.Text(module.Enums[node.A].Key));
                case TypeKind.Opaque:
                    return Identifier(module.Text(module.Opaques[node.A].Key));
                case TypeKind.Array:
                    return Spell(new TypeId(node.A)) + "*";
                default:
                    return Primitive(node.Kind);
            }
        }

        private static string Primitive(TypeKind kind) => kind switch
        {
            TypeKind.Void => "void",
            TypeKind.Bool => "bool",
            TypeKind.I8 or TypeKind.CSChar => "sbyte",
            TypeKind.U8 or TypeKind.CChar or TypeKind.CUChar => "byte",
            TypeKind.I16 or TypeKind.CShort => "short",
            TypeKind.U16 or TypeKind.CUShort => "ushort",
            TypeKind.I32 or TypeKind.CInt => "int",
            TypeKind.U32 or TypeKind.CUInt => "uint",
            TypeKind.I64 or TypeKind.CLongLong => "long",
            TypeKind.U64 or TypeKind.CULongLong => "ulong",
            TypeKind.ISize => "nint",
            TypeKind.USize => "nuint",
            TypeKind.CLong => "CLong",
            TypeKind.CULong => "CULong",
            TypeKind.F32 => "float",
            TypeKind.F64 => "double",
            _ => throw new NotSupportedException("the type " + kind + " has no C# spelling"),
        };
    }

    private static string Identifier(string name) => _keywords.Contains(name) ? "@" + name : name;

    private static string Quote(string text)
    {
        var quoted = new StringBuilder("\"");
        foreach (char c in text)
        {
            quoted.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ => c.ToString(),
            });
        }

        return quoted.Append('"').ToString();
    }
}
